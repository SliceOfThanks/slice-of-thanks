"""Copies shared/gerald.json (Gerald's note styles, notes and Reserve vibes) into the two places that use it:
the prototype (between the GERALD_JSON markers) and the api (supabase/functions/api/lib/gerald-data.ts).
Run after editing shared/gerald.json, then run tools/build_app.py.
"""
import json, pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
data = json.loads((ROOT / "shared/gerald.json").read_text())
data.pop("_about", None)
blob = json.dumps(data, ensure_ascii=False, separators=(",", ":"))

proto = ROOT / "prototype/slice-of-thanks-prototype.html"
s = proto.read_text()
a, b = "/*GERALD_JSON*/", "/*END_GERALD_JSON*/"
if s.count(a) != 1 or s.count(b) != 1:
    sys.exit("sync_gerald: GERALD_JSON markers not found in the prototype")
s = s[: s.index(a) + len(a)] + blob + s[s.index(b):]
proto.write_text(s)

(ROOT / "supabase/functions/api/lib/gerald-data.ts").write_text(
    "// Generated by tools/sync_gerald.py from shared/gerald.json. Do not edit here.\n"
    "// deno-lint-ignore-file\nexport const GERALD: any = " + blob + ";\n")
print("gerald data synced:", len(blob), "bytes")
